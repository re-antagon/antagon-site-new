export const getItemTitle = (itemName: string): string => {
  if (!itemName) return ''
  const cleanName = itemName.trim()
  const lowerName = cleanName.toLowerCase()
  if (customRuItemNames[cleanName]) {
    return customRuItemNames[cleanName]
  }
  if (customRuItemNames[lowerName]) {
    return customRuItemNames[lowerName]
  }
  if (ruItemNames[lowerName]) {
    return ruItemNames[lowerName]
  }
  return cleanName.split('_').map(word => word.charAt(0).toUpperCase() + word.slice(1)).join(' ')
}

export const getItemWikiUrl = (itemName: string): string => {
  if (!itemName) return ''
  const cleanName = itemName.trim()
  const lowerName = cleanName.toLowerCase()
  if (localItemRoutes[cleanName]) {
    return localItemRoutes[cleanName]
  }
  if (localItemRoutes[lowerName]) {
    return localItemRoutes[lowerName]
  }
  const title = getItemTitle(itemName)
  return `https://ru.minecraft.wiki/w/${encodeURIComponent(title.replace(/ /g, '_'))}`
}

export const getItemAlt = (itemName: string): string => {
  if (!itemName) return ''
  const title = getItemTitle(itemName)
  return `Иконка ${title}.png: Спрайт для инвентаря, как показано в игре.`
}

export const getItemSrc = (itemName: string): string => {
  if (!itemName) return ''
  if (itemName.startsWith('/') || itemName.includes('.')) {
    return itemName
  }
  const cleanName = itemName.trim()
  const lowerName = cleanName.toLowerCase()
  if (customItemAssets[cleanName]) {
    return customItemAssets[cleanName]
  }
  if (customItemAssets[lowerName]) {
    return customItemAssets[lowerName]
  }
  return `/assets/items/${cleanName}.png`
}
